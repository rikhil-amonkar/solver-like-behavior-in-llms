#!/usr/bin/env python3
"""
Appendix table of the runs: generations per model, task and formal language, and programs not written
in the requested formal language under each prompt (from <root>/fl_compliance.json, written by
scripts/fl_compliance_report.py). DeepSeek's second-FL runs are excluded (API drift; docs/CROSS_FL_DESIGN.md).

Usage:
    python scripts/paper_runs_table.py --paper /local-ssd/hz466/solver-like-paper
"""
import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MODELS = [("deepseek", "DeepSeek"), ("gpt", "GPT-OSS"), ("qwen", "Qwen")]
TASKS = [("calendar", "Calendar"), ("meeting", "Meeting"), ("zebralogic", "ZebraLogic"), ("blocksworld", "BlocksWorld")]
FLS = {"calendar": ["python", "z3"], "meeting": ["python", "z3"], "zebralogic": ["python", "z3"], "blocksworld": ["python", "pddl"]}
FL_NAMES = {"python": "Python", "z3": "Z3", "pddl": "PDDL"}
NATIVE = {"calendar": "python", "meeting": "python", "zebralogic": "z3", "blocksworld": "pddl"}  # the FL DeepSeek is run in
CONDS = ["baseline", "caution_a", "caution_b"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", default="/local-ssd/hz466/solver-like-paper")
    ap.add_argument("--tag", default="gemma_v11_b5t")
    args = ap.parse_args()
    rows = json.load(open(REPO / f"output/paper/ontology_traces_{args.tag}.json"))
    rows += [r for r in json.load(open(REPO / f"output/paper/ontology_traces_{args.tag}_output_crossfl.json"))
             if r["model"] != "deepseek"]
    flags = {}
    for root in ("output", "output_crossfl"):
        flags.update(json.load(open(REPO / root / "fl_compliance.json")))
    lines = [r"\begin{tabular}{lllrccc}", r"\toprule",
             r" & & & & \multicolumn{3}{c}{Not in requested FL} \\", r"\cmidrule(lr){5-7}",
             r"Model & Task & FL & Generations & 0 & A & B \\", r"\midrule"]
    total = 0
    for mi, (m, mname) in enumerate(MODELS):
        first = True
        for t, tname in TASKS:
            for fl in FLS[t]:
                n = sum(r["model"] == m and r["task"] == t and r["fl"] == fl for r in rows)
                if not n:
                    continue
                total += n
                root = "output" if fl == NATIVE[t] else "output_crossfl"
                bad = ["--" if fl == "pddl" else
                       str(sum(x["compliant"] is False for x in flags.get(f"{root}/{m}/{t}/{c}_execution.json", {}).values()))
                       for c in CONDS]
                lines.append(" & ".join([mname if first else "", tname, FL_NAMES[fl], str(n), *bad]) + r" \\")
                first = False
        if mi < len(MODELS) - 1:
            lines.append(r"\midrule")
    lines += [r"\midrule", rf"Total & & & {total:,} & & & \\".replace(",", "{,}"), r"\bottomrule", r"\end{tabular}"]
    (Path(args.paper) / "tables/runs.tex").write_text(
        "% generated by solver-like-behavior-in-llms/scripts/paper_runs_table.py; do not edit\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
